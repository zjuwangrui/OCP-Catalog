/** Builds a chain from the recipe below — the exact procedure each port runs. */
function buildChain(core, hops) {
  const chain = [];
  for (const hop of hops) {
    const unsigned = {
      catalog_id: hop.catalog_id,
      hop: hop.hop,
      role: hop.role,
      settles: hop.settles,
      chain_complete: hop.chain_complete,
      alg: 'EdDSA',
      kid: hop.kid,
      signed_at: hop.signed_at,
    };
    const node = NODES.find((n) => n.catalogId === hop.catalog_id);
    chain.push(signChainNode({ privateJwk: node.privateJwk, core, chainPrefix: chain, node: unsigned }));
  }
  return chain;
}

const HOPS = NODES.map((node, index) => ({
  catalog_id: node.catalogId,
  hop: index + 1,
  role: node.role,
  settles: node.settles,
  chain_complete: true,
  kid: node.kid,
  signed_at: SIGNED_AT[index],
}));

const chain = buildChain(CORE, HOPS);
const token = { ...CORE, complete: recomputeComplete(chain), chain };

/** A deep copy with one member replaced, for the mutation cases. */
function mutate(fn) {
  const copy = structuredClone(token);
  fn(copy);
  return copy;
}

