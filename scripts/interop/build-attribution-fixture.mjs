/**
 * Regenerates `packages/ocp-crypto/fixtures/interop/attribution-v1.json`.
 *
 *     node --experimental-strip-types --import ./scripts/interop/register-ts.mjs \
 *          scripts/interop/build-attribution-fixture.mjs
 *
 * The fixture is the contract the TypeScript, Python and Go implementations are
 * held to. It carries, in one file:
 *
 * - **Fixed keys**, derived from literal seeds rather than generated, so the
 *   file is reproducible and a diff means a real change.
 * - **An issuance recipe** — the core claims and every hop's fields including
 *   `signed_at` — so all three languages build the same token with no clock.
 * - **`expected_signing_input`**, the canonical bytes each hop signs. This is
 *   the field that makes a mismatch debuggable: when Go's token disagrees, the
 *   question is always "whose canonicalization drifted", and this answers it
 *   without a signature in the way.
 * - **`expected_token`**, which every signer must reproduce *byte for byte*.
 *   That is a stronger assertion than mutual verifiability and it is available
 *   for free: Ed25519 is deterministic and OCP-JCS fixes the bytes, so two
 *   correct implementations have no room to differ.
 * - **Negative cases** covering §7.1 rows 1–9, each with the exact error code
 *   and hop number the verifier must report. Rows 10 and 11 need registry state
 *   and are tested per-language instead.
 *
 * Generated by the TypeScript implementation because it is the reference one —
 * but nothing here is TypeScript-shaped, and a mismatch is not automatically
 * the other language's bug.
 */
